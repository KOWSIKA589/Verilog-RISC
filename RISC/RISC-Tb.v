// ============================================================
// TESTBENCH FOR 16-BIT RISC PROCESSOR
// ============================================================

`timescale 1ns/1ps

module RISC16_TB;

    // ========================================================
    // CLOCK AND RESET
    // ========================================================

    reg clk;
    reg reset;

    // ========================================================
    // INSTANTIATE PROCESSOR
    // ========================================================

    RISC16 uut (
        .clk(clk),
        .reset(reset)
    );

    // ========================================================
    // CLOCK GENERATION
    // 10 ns clock period
    // ========================================================

    always #5 clk = ~clk;

    // ========================================================
    // INSTRUCTION ENCODING
    // ========================================================

    initial begin

        clk = 0;
        reset = 1;

        // ----------------------------------------------------
        // Wait for reset
        // ----------------------------------------------------

        #10;

        reset = 0;

        // ====================================================
        // PROGRAM
        // ====================================================

        // ----------------------------------------------------
        // Instruction 0:
        // ADDI R1, R0, 5
        //
        // R1 = R0 + 5
        // R1 = 5
        // ----------------------------------------------------

        uut.instruction_memory[0] =
            {4'b0100, 3'b001, 3'b000, 6'd5};


        // ----------------------------------------------------
        // Instruction 1:
        // ADDI R2, R0, 10
        //
        // R2 = R0 + 10
        // R2 = 10
        // ----------------------------------------------------

        uut.instruction_memory[1] =
            {4'b0100, 3'b010, 3'b000, 6'd10};


        // ----------------------------------------------------
        // Instruction 2:
        // ADD R3, R1, R2
        //
        // R3 = R1 + R2
        // R3 = 5 + 10
        // R3 = 15
        // ----------------------------------------------------

        uut.instruction_memory[2] =
            {4'b0000, 3'b011, 3'b001, 3'b010, 3'b000};


        // ----------------------------------------------------
        // Instruction 3:
        // ST R3, [R0 + 0]
        //
        // Memory[0] = R3
        // Memory[0] = 15
        // ----------------------------------------------------

        uut.instruction_memory[3] =
            {4'b0110, 3'b011, 3'b000, 6'd0};


        // ----------------------------------------------------
        // Instruction 4:
        // LD R4, [R0 + 0]
        //
        // R4 = Memory[0]
        // R4 = 15
        // ----------------------------------------------------

        uut.instruction_memory[4] =
            {4'b0101, 3'b100, 3'b000, 6'd0};


        // ----------------------------------------------------
        // Instruction 5:
        // HALT
        // ----------------------------------------------------

        uut.instruction_memory[5] =
            {4'b1111, 12'b0};


        // ====================================================
        // WAIT FOR PROGRAM EXECUTION
        // ====================================================

        #100;


        // ====================================================
        // DISPLAY RESULTS
        // ====================================================

        $display("---------------------------------------");
        $display("       16-BIT RISC PROCESSOR");
        $display("---------------------------------------");

        $display("R1 = %d", uut.registers[1]);
        $display("R2 = %d", uut.registers[2]);
        $display("R3 = %d", uut.registers[3]);
        $display("R4 = %d", uut.registers[4]);

        $display("Memory[0] = %d", uut.data_memory[0]);

        $display("PC = %d", uut.PC);

        $display("---------------------------------------");


        // ====================================================
        // CHECK RESULT
        // ====================================================

        if ((uut.registers[3] == 16'd15) &&
            (uut.registers[4] == 16'd15) &&
            (uut.data_memory[0] == 16'd15)) begin

            $display("TEST PASSED");

        end

        else begin

            $display("TEST FAILED");

        end

        $display("---------------------------------------");


        // ====================================================
        // END SIMULATION
        // ====================================================

        $finish;

    end

endmodule